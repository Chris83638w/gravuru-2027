import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {once} from 'node:events';
import {createWorkshop} from './http.mjs';
import {createPreviewServer} from '../configurator/variant-m/server.mjs';
import {moduleProfileTestSource,steelModuleSwitches} from './test-fixtures/module-profile-source.mjs';
import {vectorLogoAllowed,quote} from '../configurator/variant-m/contract.mjs';
import {prepareShopProduct} from './shop-preparation.mjs';
import {capturePersonalization,personalizationForSnapshot} from './cart-personalization.mjs';

test('merchant module flow: confirm exact source/options, create two local profiles, reopen same editor and reject forged logo',async t=>{
 const directory=fs.mkdtempSync(path.join(os.tmpdir(),'g27-modules-http-')),filename=path.join(directory,'workshop.sqlite');
 const original=moduleProfileTestSource(),workshop=createWorkshop({filename,seedConfig:original.config,legacy:{purchasing:{}}});
 const source=workshop.repository.create(original),before=structuredClone(source.document);
 const server=createPreviewServer({outputDirectory:directory,workshop});server.listen(0,'127.0.0.1');await once(server,'listening');
 t.after(async()=>{await new Promise(r=>server.close(r));workshop.close();assert.ok(directory.startsWith(path.join(os.tmpdir(),'g27-modules-http-')));fs.rmSync(directory,{recursive:true,force:true});});
 const base='http://127.0.0.1:'+server.address().port,api='/api/workshop/configurator-modules';
 const read=async route=>{const response=await fetch(base+route),data=await response.json();assert.equal(response.status,200,JSON.stringify(data));return data;};
 const {csrfToken}=await read('/api/workshop/session');
 const post=async(data,token=csrfToken)=>{const r=await fetch(base+api,{method:'POST',headers:{'Content-Type':'application/json','X-Gravuru-CSRF':token},body:JSON.stringify(data)});return {status:r.status,data:await r.json()};};
 const ok=async data=>{const r=await post(data);assert.equal(r.status,200,JSON.stringify(r.data));return r.data;};
 assert.equal((await post({action:'profile-create',document:{name:'Bad token',modules:steelModuleSwitches}},'bad')).status,403);
 const initial=await read(api);assert.equal(initial.sources.length,1);assert.equal(initial.scopes[0].subcategoryId,source.id);
 const created=[];
 for(const logo of [true,false]){
  const profile=await ok({action:'profile-create',document:{name:logo?'Türschild mit Logo':'Türschild ohne Logo',modules:{...steelModuleSwitches,logo}}});
  const draft=await ok({action:'template-draft',name:profile.document.name,scope:{lineId:'native-products',subcategoryId:source.id},sourceKeys:[source.id]});
  draft.targets[0].moduleProfile={id:profile.id,revision:profile.revision};
  const template=await ok({action:'template-create',document:draft});
  const plan=await ok({action:'plan',templateId:template.id,templateRevision:template.revision,creationKey:logo?'with-logo':'without-logo',products:[{key:'sign',targetKey:source.id,name:profile.document.name}]});
  assert.equal(plan.valid,true,JSON.stringify(plan.issues));
  assert.equal((await post({action:'execute',planId:plan.id,planHash:plan.planHash,confirmationId:'missing'})).status,409);
  assert.equal((await post({action:'confirm',planId:plan.id,planHash:plan.planHash,accepted:false})).status,422);
  const confirmation=await ok({action:'confirm',planId:plan.id,planHash:plan.planHash,accepted:true});
  const args={action:'execute',planId:plan.id,planHash:plan.planHash,confirmationId:confirmation.confirmationId},result=await ok(args);
  assert.equal(result.created,1);assert.equal(result.shopifyWrites,0);assert.equal((await ok(args)).replayed,true);
  const record=workshop.repository.get(result.products[0].productId);created.push(record);
  assert.equal(record.status,'draft');assert.equal(record.publishedRevision,null);
  assert.deepEqual(record.document.config.profile.designs,before.config.profile.designs);
  assert.deepEqual(record.document.elementRights,before.elementRights);
  assert.deepEqual(record.document.config.profile.optionGroups,before.config.profile.optionGroups);
  assert.equal(vectorLogoAllowed(record.document.config),logo);
  const loaded=(await read('/models.json?configuration='+record.id+'&revision=1'))[0];
  assert.equal(loaded.universal.moduleProfile.modules.logo,logo);
  assert.equal(quote(loaded.universal,[],loaded.universal.profile.defaultDesignId,{mounting:'two'}).unitCents,2298);
  const preview=prepareShopProduct(record);assert.equal(preview.extras.logoCents,logo?1299:undefined);assert.equal(preview.shopReady,false);
 }
 assert.deepEqual(workshop.repository.get(source.id).document,before);
 const noLogo=created[1],response=await fetch(base+'/api/workshop/customer-vector-logo/preview',{method:'POST',headers:{'Content-Type':'application/json','X-Gravuru-CSRF':csrfToken},body:JSON.stringify({productId:noLogo.id,productRevision:1,name:'test.svg',original:Buffer.from('<svg/>').toString('base64')})});
 assert.equal(response.status,422);assert.match((await response.json()).error.message,/nicht freigegeben/);
 const pricing={schema:'gravuru-personalization-pricing/v1',enabled:true,productId:'gid://shopify/Product/101',revision:1,currency:'EUR',variants:{301:1999},extraMotifCents:169,extraPhotoCents:999};
 const captured=capturePersonalization(pricing,{variantId:'301',baseCents:1999,document:noLogo.document});
 assert.deepEqual(captured.moduleProfile,noLogo.document.config.moduleProfile);
 const malicious={selection:{price:{chargedUploads:1,chargedLogos:0,additionalMotifs:0}}};
 assert.throws(()=>personalizationForSnapshot(captured,malicious),{code:'cart_personalization'});
 for(const route of ['/werkstatt/module/','/workshop-ui/module-profiles.mjs','/workshop-ui/module-profiles.css'])assert.equal((await fetch(base+route)).status,200,route);
 assert.match(await (await fetch(base+'/werkstatt/konfis/')).text(),/\/werkstatt\/module\//);
 assert.equal((await post({action:'profile-create',document:{name:'Unexpected',modules:steelModuleSwitches},extra:true})).status,422);
});
