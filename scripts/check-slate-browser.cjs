const fs=require('node:fs');
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
(async()=>{
 const plans=JSON.parse(fs.readFileSync(process.env.SLATE_PLAN||'../slate-package-v4/shopify-plan.json'));
 const p=plans.find(p=>p.sizeKey==='GT-SN-RE-220X140');
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});const errors=[];
 page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
 await page.goto('http://127.0.0.1:8978/?configuration='+p.productId+'&revision=1',{waitUntil:'networkidle',timeout:120000});
 const editor=page.frames().find(f=>f.url().endsWith('/editor.html'));
 try{await editor.locator('gravuru-configurator').waitFor({state:'visible',timeout:120000});}catch(e){errors.push(e.message);}
 const root=editor.locator('gravuru-configurator');
 await root.locator('.m-memorial-photo').waitFor({state:'visible',timeout:60000});
 assert.equal(await root.locator('[data-slate-group-heading]:visible').count(),0);
 assert.equal(await root.locator('[data-slate-accessory]').count(),3);
 assert.ok(await root.locator('[data-slate-accessory] img').count()>=3);
 await root.locator('[data-picture-group="mounting"][data-picture-option="AH02"]').click();
 assert.equal(await root.locator('[data-slate-group-heading]:visible').count(),1);
 assert.equal(await root.locator('[data-picture-group="ah-farbe-4"]:visible').count(),0);
 assert.equal(await root.locator('[data-picture-group="ah-farbe-2"]:visible').count(),5);
 await root.locator('[data-picture-group="ah-farbe-2"][data-picture-option="gold"]').click();
 await root.locator('[data-slate-accessory="silikon"]').click();
 assert.match(await root.locator('[data-fk-total]').innerText(),/35,97/);
 const state=await root.evaluate(el=>({options:el.state.mOptions,images:[...el.shadowRoot.querySelectorAll('.m-slate-images img')].filter(i=>i.complete&&!i.naturalWidth).length}));
 assert.equal(state.images,0);
 console.log(JSON.stringify({checked:'AH02 Gold plus Silikon',price:'35,97',state}));
 await page.screenshot({path:'../slate-browser-accessories.png',fullPage:true});
 await root.locator('[data-picture-group="mounting"][data-picture-option="K00"]').click();
 assert.equal(await root.locator('[data-slate-group-heading]:visible').count(),0);
 assert.equal(await root.locator('[data-picture-group^="ah-farbe-"]:visible').count(),0);
 assert.match(await root.locator('[data-fk-total]').innerText(),/28,98/);
 await root.locator('[data-slate-accessory="silikon"]').click();
 await root.locator('#ux-tab-design').click();
 const cards=root.locator('[data-c-design]');assert.ok(await cards.count()>=104);
 const filter=root.locator('[data-m-filter="collection"]');await filter.selectOption('Hunde');
 await editor.waitForFunction(()=>{const r=document.querySelector('gravuru-configurator')?.shadowRoot;return r&&[...r.querySelectorAll('[data-c-design]')].some(c=>c.hidden);});
 const dogs=await root.locator('[data-c-design]:not([hidden])').count();assert.ok(dogs>0&&dogs<await cards.count());
 console.log(JSON.stringify({filter:'Hunde',designs:dogs}));
 await filter.selectOption('');
 await cards.nth(1).click();
 await root.locator('#ux-tab-options').click();
 await root.locator('#ux-tab-design').click();await cards.first().click();
 await root.locator('#ux-tab-upload').click();
 await root.locator('[data-ux-file]').setInputFiles('../gravuru-schiefer-katalog/materialien/zubehoer/bilder/vorlage-foto-mensch.jpg');
 await root.locator('.ux-upload-row').waitFor({state:'visible',timeout:30000});
 assert.match(await root.locator('[data-fk-total]').innerText(),/31,98/);
 console.log(JSON.stringify({photo:'Original ohne Fotofeld + 1 Upload',price:'31,98'}));
 await page.screenshot({path:'../slate-browser-first.png',fullPage:true});
 console.log(JSON.stringify({title:await page.title(),frames:page.frames().map(f=>f.url()),body:(await page.locator('body').innerText()).slice(0,1800),errors}));
 assert.deepEqual(errors,[]);
 await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1;});
